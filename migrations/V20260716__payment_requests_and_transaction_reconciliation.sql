-- Recover one request for every distinct PayOS booking transaction before using
-- the single legacy booking cache as a fallback. A booking may have both a
-- deposit link and a remaining-payment link, while bookings only retained the
-- most recently generated link.
WITH raw_transaction_evidence AS (
    SELECT
        pt.payment_transaction_id,
        pt.booking_id,
        COALESCE(pt.user_id, b.parent_id) AS user_id,
        pt.purpose,
        pt.amount,
        pt.currency,
        pt.description,
        pt.destination_account_bank_bin,
        pt.destination_account_bank_name,
        pt.order_code AS stored_order_code,
        pt.created_at,
        pt.paid_at,
        pt.provider_payload AS raw_provider_payload,
        b.payment_code AS cached_payment_link_id,
        b.payos_bin,
        b.payos_account_number,
        b.payos_account_name,
        b.payos_description,
        b.payos_checkout_url,
        b.payos_qr_code,
        b.payment_due_at,
        b.deposit_amount,
        b.remaining_amount,
        b.final_price,
        NULLIF(BTRIM(COALESCE(
            pt.provider_payload #>> '{data,orderCode}',
            pt.provider_payload ->> 'orderCode'
        )), '') AS payload_order_code,
        CASE
            WHEN jsonb_typeof(pt.provider_payload -> 'transactions') = 'array'
                THEN NULLIF(BTRIM(
                    pt.provider_payload ->> 'amount'
                ), '')
        END AS provider_request_amount,
        NULLIF(BTRIM(COALESCE(
            pt.provider_payload #>> '{data,paymentLinkId}',
            pt.provider_payload ->> 'id',
            pt.payment_link_id
        )), '') AS recovered_payment_link_id
    FROM public.payment_transactions pt
    JOIN public.bookings b ON b.booking_id = pt.booking_id
    WHERE pt.channel = 'PayOS'
      AND pt.legacy_reconciliation_version = 'V20260716'
      AND pt.status = 'Succeeded'
      AND pt.booking_id IS NOT NULL
      AND pt.purpose IN ('BookingDeposit', 'BookingRemaining')
), transaction_evidence AS (
    SELECT
        r.*,
        CASE
            WHEN r.payload_order_code ~ '^[0-9]{1,18}$'
                THEN r.payload_order_code::BIGINT
            ELSE r.stored_order_code
        END AS recovered_order_code,
        CASE
            WHEN r.provider_request_amount ~
                '^[0-9]{1,13}([.][0-9]{1,2})?$'
                THEN r.provider_request_amount::NUMERIC(15, 2)
            ELSE NULL
        END AS recovered_provider_request_amount
    FROM raw_transaction_evidence r
), normalized_transaction_evidence AS (
    SELECT
        e.*,
        CASE
            WHEN e.purpose = 'BookingDeposit' THEN 'deposit'
            WHEN e.purpose = 'BookingRemaining' THEN 'remaining'
            WHEN e.recovered_order_code / 100000000000 = 1
                THEN 'deposit'
            WHEN e.recovered_order_code / 100000000000 = 2
                THEN 'remaining'
            ELSE 'legacy_unknown'
        END AS phase
    FROM transaction_evidence e
), request_transaction_evidence AS (
    SELECT
        e.*,
        CASE
            WHEN e.phase = 'deposit' THEN COALESCE(
                CASE
                    WHEN e.deposit_amount > 0 THEN e.deposit_amount
                END,
                e.recovered_provider_request_amount
            )
            WHEN e.phase = 'remaining' THEN COALESCE(
                CASE
                    WHEN e.remaining_amount > 0 THEN e.remaining_amount
                END,
                e.recovered_provider_request_amount
            )
            ELSE COALESCE(
                CASE
                    WHEN e.final_price > 0 THEN e.final_price
                END,
                e.recovered_provider_request_amount
            )
        END AS raw_expected_amount
    FROM normalized_transaction_evidence e
)
INSERT INTO public.payment_requests (
    booking_id,
    user_id,
    provider,
    phase,
    order_code,
    payment_link_id,
    amount,
    currency,
    status,
    destination_bank_bin,
    destination_bank_name,
    display_account_number,
    display_account_name,
    description,
    checkout_url,
    qr_code,
    expires_at,
    provider_payload,
    created_at,
    updated_at
)
SELECT
    e.booking_id,
    e.user_id,
    'PayOS',
    e.phase,
    e.recovered_order_code,
    e.recovered_payment_link_id,
    CASE
        WHEN e.raw_expected_amount > 0 THEN e.raw_expected_amount
        ELSE NULL
    END,
    COALESCE(NULLIF(e.currency, ''), 'VND'),
    'PAID',
    COALESCE(
        e.destination_account_bank_bin,
        CASE
            WHEN e.cached_payment_link_id = e.recovered_payment_link_id
                THEN e.payos_bin
        END
    ),
    e.destination_account_bank_name,
    CASE
        WHEN e.cached_payment_link_id = e.recovered_payment_link_id
            THEN e.payos_account_number
    END,
    CASE
        WHEN e.cached_payment_link_id = e.recovered_payment_link_id
            THEN e.payos_account_name
    END,
    COALESCE(
        CASE
            WHEN e.cached_payment_link_id = e.recovered_payment_link_id
                THEN e.payos_description
        END,
        e.description
    ),
    CASE
        WHEN e.cached_payment_link_id = e.recovered_payment_link_id
            THEN e.payos_checkout_url
    END,
    CASE
        WHEN e.cached_payment_link_id = e.recovered_payment_link_id
            THEN e.payos_qr_code
    END,
    CASE
        WHEN e.cached_payment_link_id = e.recovered_payment_link_id
            THEN e.payment_due_at
    END,
    (
        CASE
            WHEN jsonb_typeof(e.raw_provider_payload) = 'object'
                THEN e.raw_provider_payload
            ELSE jsonb_build_object(
                'legacyPayload',
                e.raw_provider_payload
            )
        END
        || jsonb_build_object(
            '_source', 'legacy_payment_transaction',
            'paymentTransactionId', e.payment_transaction_id,
            'orderCode', e.recovered_order_code,
            'paymentLinkId', e.recovered_payment_link_id
        )
    ),
    COALESCE(e.created_at, e.paid_at, CURRENT_TIMESTAMP),
    COALESCE(e.paid_at, e.created_at, CURRENT_TIMESTAMP)
FROM request_transaction_evidence e
WHERE e.recovered_payment_link_id IS NOT NULL
   OR e.recovered_order_code IS NOT NULL
ON CONFLICT DO NOTHING;

-- Historical polling stored one payment-link row using the request total and
-- only copied fields from transactions[last]. Expand a trustworthy array into
-- one ledger row per real bank transfer before normalizing/attaching rows.
-- Missing/duplicate references, invalid amounts/timestamps, or references that
-- already belong to another ledger row are not guessed: the related request is
-- forced to review instead of being allowed to reconcile as Matched.
CREATE TEMP TABLE legacy_payos_transaction_expansion
ON COMMIT DROP
AS
WITH array_elements AS (
    SELECT
        pt.payment_transaction_id AS source_payment_transaction_id,
        pt.provider_transaction_id AS existing_reference,
        pt.order_code AS stored_order_code,
        pt.payment_link_id AS stored_payment_link_id,
        pt.provider_payload AS root_provider_payload,
        element.value AS element_payload,
        element.ordinality::INTEGER AS element_ordinal
    FROM public.payment_transactions pt
    CROSS JOIN LATERAL jsonb_array_elements(
        pt.provider_payload -> 'transactions'
    ) WITH ORDINALITY AS element(value, ordinality)
    WHERE pt.channel = 'PayOS'
      AND pt.legacy_reconciliation_version = 'V20260716'
      AND pt.status = 'Succeeded'
      AND pt.booking_id IS NOT NULL
      AND pt.purpose IN ('BookingDeposit', 'BookingRemaining')
      AND jsonb_typeof(pt.provider_payload -> 'transactions') = 'array'
), extracted_elements AS (
    SELECT
        e.*,
        NULLIF(NULLIF(BTRIM(
            e.element_payload ->> 'reference'
        ), ''), '0') AS element_reference,
        NULLIF(BTRIM(
            e.element_payload ->> 'amount'
        ), '') AS element_amount_text,
        NULLIF(BTRIM(
            e.element_payload ->> 'transactionDateTime'
        ), '') AS element_transaction_datetime,
        CASE
            WHEN NULLIF(BTRIM(COALESCE(
                e.root_provider_payload #>> '{data,orderCode}',
                e.root_provider_payload ->> 'orderCode'
            )), '') ~ '^[0-9]{1,18}$'
                THEN NULLIF(BTRIM(COALESCE(
                    e.root_provider_payload #>> '{data,orderCode}',
                    e.root_provider_payload ->> 'orderCode'
                )), '')::BIGINT
            ELSE e.stored_order_code
        END AS recovered_order_code,
        COALESCE(
            NULLIF(BTRIM(
                e.root_provider_payload #>> '{data,paymentLinkId}'
            ), ''),
            NULLIF(BTRIM(
                e.root_provider_payload ->> 'id'
            ), ''),
            NULLIF(BTRIM(e.stored_payment_link_id), '')
        ) AS recovered_payment_link_id
    FROM array_elements e
), qualified_elements AS (
    SELECT
        e.*,
        jsonb_typeof(e.element_payload) = 'object'
            AS element_is_object,
        CASE
            WHEN e.element_amount_text ~
                '^[0-9]{1,13}([.][0-9]{1,2})?$'
                THEN e.element_amount_text::NUMERIC(15, 2) > 0
            ELSE FALSE
        END AS amount_is_valid,
        CASE
            WHEN e.element_transaction_datetime ~
                '^[0-9]{4}-[0-9]{2}-[0-9]{2}[ T][0-9]{2}:[0-9]{2}:[0-9]{2}([.][0-9]{1,6})?(Z|[+-][0-9]{2}:?[0-9]{2})$'
                THEN pg_input_is_valid(
                    e.element_transaction_datetime,
                    'timestamp with time zone'
                )
            WHEN e.element_transaction_datetime ~
                '^[0-9]{4}-[0-9]{2}-[0-9]{2}[ T][0-9]{2}:[0-9]{2}:[0-9]{2}([.][0-9]{1,6})?$'
                THEN pg_input_is_valid(
                    replace(
                        e.element_transaction_datetime,
                        'T',
                        ' '
                    ),
                    'timestamp without time zone'
                )
            ELSE FALSE
        END AS timestamp_is_valid,
        COALESCE(char_length(
            e.element_payload ->> 'code'
        ) <= 50, TRUE)
        AND COALESCE(char_length(
            e.element_payload ->> 'counterAccountBankId'
        ) <= 50, TRUE)
        AND COALESCE(char_length(
            e.element_payload ->> 'counterAccountBankName'
        ) <= 100, TRUE)
        AND COALESCE(char_length(
            e.element_payload ->> 'counterAccountNumber'
        ) <= 50, TRUE)
        AND COALESCE(char_length(
            e.element_payload ->> 'counterAccountName'
        ) <= 200, TRUE)
        AND COALESCE(char_length(
            e.element_payload ->> 'accountNumber'
        ) <= 50, TRUE)
        AND COALESCE(char_length(
            e.element_payload ->> 'accountName'
        ) <= 200, TRUE)
        AND COALESCE(char_length(
            e.element_payload ->> 'virtualAccountNumber'
        ) <= 50, TRUE)
        AND COALESCE(char_length(
            e.element_payload ->> 'virtualAccountName'
        ) <= 200, TRUE)
            AS bounded_fields_are_valid,
        EXISTS (
            SELECT 1
            FROM public.payment_transactions other
            WHERE other.payment_transaction_id
                    <> e.source_payment_transaction_id
              AND other.channel = 'PayOS'
              AND NULLIF(BTRIM(
                  other.provider_transaction_id
              ), '') = e.element_reference
        ) AS reference_conflicts
    FROM extracted_elements e
), source_quality AS (
    SELECT
        source_payment_transaction_id,
        BOOL_AND(
            element_is_object
            AND element_reference IS NOT NULL
            AND char_length(element_reference) <= 255
            AND amount_is_valid
            AND timestamp_is_valid
            AND bounded_fields_are_valid
            AND NOT reference_conflicts
        ) AS all_elements_trustworthy,
        COUNT(DISTINCT element_reference) = COUNT(*)
            AS references_are_unique
    FROM qualified_elements
    GROUP BY source_payment_transaction_id
), trustworthy_elements AS (
    SELECT
        e.*,
        CASE
            WHEN e.element_amount_text ~
                '^[0-9]{1,13}([.][0-9]{1,2})?$'
                THEN e.element_amount_text::NUMERIC(15, 2)
        END AS element_amount,
        CASE
            WHEN e.element_transaction_datetime ~
                '^[0-9]{4}-[0-9]{2}-[0-9]{2}[ T][0-9]{2}:[0-9]{2}:[0-9]{2}([.][0-9]{1,6})?(Z|[+-][0-9]{2}:?[0-9]{2})$'
                 AND pg_input_is_valid(
                     e.element_transaction_datetime,
                     'timestamp with time zone'
                 )
                THEN e.element_transaction_datetime::TIMESTAMPTZ
                    AT TIME ZONE 'UTC'
            WHEN e.element_transaction_datetime ~
                '^[0-9]{4}-[0-9]{2}-[0-9]{2}[ T][0-9]{2}:[0-9]{2}:[0-9]{2}([.][0-9]{1,6})?$'
                 AND pg_input_is_valid(
                     replace(
                         e.element_transaction_datetime,
                         'T',
                         ' '
                     ),
                     'timestamp without time zone'
                 )
                THEN (
                    replace(
                        e.element_transaction_datetime,
                        'T',
                        ' '
                    )::TIMESTAMP
                    AT TIME ZONE 'Asia/Ho_Chi_Minh'
                ) AT TIME ZONE 'UTC'
        END AS element_paid_at
    FROM qualified_elements e
    JOIN source_quality quality
      ON quality.source_payment_transaction_id
            = e.source_payment_transaction_id
    WHERE quality.all_elements_trustworthy
      AND quality.references_are_unique
)
SELECT
    e.*,
    ROW_NUMBER() OVER (
        PARTITION BY e.source_payment_transaction_id
        ORDER BY
            CASE
                WHEN NULLIF(BTRIM(e.existing_reference), '')
                        = e.element_reference
                    THEN 0
                ELSE 1
            END,
            e.element_ordinal DESC
    ) AS anchor_rank
FROM trustworthy_elements e;

-- Any array that did not qualify for expansion is ambiguous. Keep its original
-- evidence intact, but remove the expected amount from its request so the
-- normal aggregate reconciliation below produces Unexpected/RequiresReview.
WITH invalid_array_sources AS (
    SELECT
        pt.payment_transaction_id,
        pt.booking_id,
        pt.purpose,
        CASE
            WHEN NULLIF(BTRIM(COALESCE(
                pt.provider_payload #>> '{data,orderCode}',
                pt.provider_payload ->> 'orderCode'
            )), '') ~ '^[0-9]{1,18}$'
                THEN NULLIF(BTRIM(COALESCE(
                    pt.provider_payload #>> '{data,orderCode}',
                    pt.provider_payload ->> 'orderCode'
                )), '')::BIGINT
            ELSE pt.order_code
        END AS recovered_order_code,
        COALESCE(
            NULLIF(BTRIM(
                pt.provider_payload #>> '{data,paymentLinkId}'
            ), ''),
            NULLIF(BTRIM(
                pt.provider_payload ->> 'id'
            ), ''),
            NULLIF(BTRIM(pt.payment_link_id), '')
        ) AS recovered_payment_link_id
    FROM public.payment_transactions pt
    WHERE pt.channel = 'PayOS'
      AND pt.legacy_reconciliation_version = 'V20260716'
      AND pt.status = 'Succeeded'
      AND pt.booking_id IS NOT NULL
      AND pt.purpose IN ('BookingDeposit', 'BookingRemaining')
      AND jsonb_typeof(pt.provider_payload -> 'transactions') = 'array'
      AND NOT EXISTS (
          SELECT 1
          FROM legacy_payos_transaction_expansion expanded
          WHERE expanded.source_payment_transaction_id
                = pt.payment_transaction_id
      )
)
UPDATE public.payment_requests pr
SET
    amount = NULL,
    status = 'REQUIRES_REVIEW',
    provider_payload = COALESCE(
        pr.provider_payload,
        '{}'::JSONB
    ) || jsonb_build_object(
        '_legacyArrayReview',
        'invalid_or_ambiguous_transactions'
    ),
    updated_at = CURRENT_TIMESTAMP
FROM invalid_array_sources invalid
WHERE pr.provider = 'PayOS'
  AND pr.booking_id = invalid.booking_id
  AND (
      (
          invalid.purpose = 'BookingDeposit'
          AND pr.phase IN ('deposit', 'legacy_unknown')
      )
      OR (
          invalid.purpose = 'BookingRemaining'
          AND pr.phase IN ('remaining', 'legacy_unknown')
      )
  )
  AND (
      (
          invalid.recovered_payment_link_id IS NOT NULL
          AND pr.payment_link_id
                = invalid.recovered_payment_link_id
      )
      OR (
          invalid.recovered_order_code IS NOT NULL
          AND pr.order_code = invalid.recovered_order_code
      )
  );

