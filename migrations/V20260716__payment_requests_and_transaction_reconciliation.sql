-- Attach each booking transaction to exactly one best request candidate.
WITH request_candidates AS (
    SELECT
        pt.payment_transaction_id,
        pr.payment_request_id,
        ROW_NUMBER() OVER (
            PARTITION BY pt.payment_transaction_id
            ORDER BY
                CASE
                    WHEN pt.purpose = 'BookingDeposit'
                         AND pr.phase = 'deposit' THEN 0
                    WHEN pt.purpose = 'BookingRemaining'
                         AND pr.phase = 'remaining' THEN 0
                    ELSE 1
                END,
                CASE
                    WHEN pt.payment_link_id IS NOT NULL
                         AND pr.payment_link_id = pt.payment_link_id
                        THEN 0
                    ELSE 1
                END,
                CASE
                    WHEN pt.order_code IS NOT NULL
                         AND pr.order_code = pt.order_code
                        THEN 0
                    ELSE 1
                END,
                pr.created_at DESC,
                pr.payment_request_id DESC
        ) AS candidate_rank
    FROM public.payment_transactions pt
    JOIN public.payment_requests pr
      ON pr.provider = 'PayOS'
     AND pr.booking_id = pt.booking_id
     AND (
         (pt.purpose = 'BookingDeposit'
          AND pr.phase IN ('deposit', 'legacy_unknown'))
         OR
         (pt.purpose = 'BookingRemaining'
          AND pr.phase IN ('remaining', 'legacy_unknown'))
     )
     AND (
         (
             pt.payment_link_id IS NOT NULL
             AND pr.payment_link_id = pt.payment_link_id
         )
         OR (
             pt.order_code IS NOT NULL
             AND pr.order_code = pt.order_code
         )
     )
    WHERE pt.payment_request_id IS NULL
      AND pt.channel = 'PayOS'
      AND pt.legacy_reconciliation_version = 'V20260716'
      AND pt.purpose IN ('BookingDeposit', 'BookingRemaining')
)
UPDATE public.payment_transactions pt
SET payment_request_id = candidate.payment_request_id,
    destination_account_bank_bin = COALESCE(
        pt.destination_account_bank_bin,
        pr.destination_bank_bin
    ),
    destination_account_bank_name = COALESCE(
        pt.destination_account_bank_name,
        pr.destination_bank_name
    )
FROM request_candidates candidate
JOIN public.payment_requests pr
  ON pr.payment_request_id = candidate.payment_request_id
WHERE candidate.candidate_rank = 1
  AND pt.payment_transaction_id = candidate.payment_transaction_id;

-- Reconcile by the aggregate received amount. Every distinct real transaction
-- remains in the ledger and contributes to its payment request.
WITH request_totals AS (
    SELECT
        pt.payment_request_id,
        pr.amount AS expected_amount,
        SUM(pt.amount) AS observed_total
    FROM public.payment_transactions pt
    JOIN public.payment_requests pr
      ON pr.payment_request_id = pt.payment_request_id
     AND pr.provider = 'PayOS'
    WHERE pt.channel = 'PayOS'
      AND pt.legacy_reconciliation_version = 'V20260716'
      AND pr.legacy_reconciliation_version IS DISTINCT FROM 'V20260716'
    GROUP BY pt.payment_request_id, pr.amount
)
UPDATE public.payment_transactions pt
SET reconciliation_status = CASE
    WHEN totals.expected_amount IS NULL THEN 'Unexpected'
    WHEN totals.observed_total < totals.expected_amount THEN 'Partial'
    WHEN totals.observed_total > totals.expected_amount THEN 'AmountMismatch'
    ELSE 'Matched'
END
FROM request_totals totals
WHERE totals.payment_request_id = pt.payment_request_id
  AND pt.channel = 'PayOS'
  AND pt.legacy_reconciliation_version = 'V20260716';

