  AND purpose IN ('BookingDeposit', 'BookingRemaining')
  AND payment_request_id IS NULL;

-- Preserve the one-active-request-per-booking-phase invariant. Prefer the link
-- still cached on the booking, then the newest request. Historical exact-paid
-- requests remain PAID; older incomplete requests become SUPERSEDED.
WITH ranked_requests AS (
    SELECT
        pr.payment_request_id,
        ROW_NUMBER() OVER (
            PARTITION BY pr.booking_id, pr.phase
            ORDER BY
                CASE
                    WHEN b.payment_code IS NOT NULL
                         AND pr.payment_link_id = b.payment_code
                        THEN 0
                    ELSE 1
                END,
                pr.created_at DESC,
                pr.payment_request_id DESC
        ) AS active_rank
    FROM public.payment_requests pr
    JOIN public.bookings b ON b.booking_id = pr.booking_id
    WHERE pr.provider = 'PayOS'
      AND pr.provider_payload ->> '_source' IN (
          'legacy_payment_transaction',
          'bookings_legacy_cache'
      )
      AND pr.legacy_reconciliation_version IS DISTINCT FROM 'V20260716'
      AND pr.phase IN ('deposit', 'remaining')
)
UPDATE public.payment_requests pr
SET status = 'SUPERSEDED',
    updated_at = CURRENT_TIMESTAMP
FROM ranked_requests ranked
WHERE ranked.payment_request_id = pr.payment_request_id
  AND ranked.active_rank > 1
  AND pr.status IN (
      'PENDING',
      'PROCESSING',
      'REQUIRES_REVIEW',
      'UNKNOWN'
  );

-- Keep request status aligned with the aggregate evidence. A legacy booking
-- timestamp by itself is not proof that the transaction ledger is complete.
WITH request_evidence AS (
    SELECT
        pr.payment_request_id,
        pr.booking_id,
        pr.phase,
        pr.payment_link_id,
        pr.amount AS expected_amount,
        pr.status AS current_status,
        COUNT(pt.payment_transaction_id) AS transaction_count,
        COALESCE(SUM(pt.amount), 0) AS observed_total
    FROM public.payment_requests pr
    LEFT JOIN public.payment_transactions pt
      ON pt.payment_request_id = pr.payment_request_id
     AND pt.channel = 'PayOS'
     AND pt.legacy_reconciliation_version = 'V20260716'
    WHERE pr.provider = 'PayOS'
      AND pr.provider_payload ->> '_source' IN (
          'legacy_payment_transaction',
          'bookings_legacy_cache'
      )
      AND pr.legacy_reconciliation_version IS DISTINCT FROM 'V20260716'
    GROUP BY
        pr.payment_request_id,
        pr.booking_id,
        pr.phase,
        pr.payment_link_id,
        pr.amount,
        pr.status
), ranked_evidence AS (
    SELECT
        evidence.*,
        ROW_NUMBER() OVER (
            PARTITION BY evidence.booking_id, evidence.phase
            ORDER BY
                CASE
                    WHEN b.payment_code IS NOT NULL
                         AND evidence.payment_link_id = b.payment_code
                        THEN 0
                    ELSE 1
                END,
                pr.created_at DESC,
                evidence.payment_request_id DESC
        ) AS active_rank
    FROM request_evidence evidence
    JOIN public.payment_requests pr
      ON pr.payment_request_id = evidence.payment_request_id
    JOIN public.bookings b ON b.booking_id = evidence.booking_id
), desired_request_status AS (
    SELECT
        evidence.payment_request_id,
        CASE
            WHEN evidence.transaction_count > 0
                 AND evidence.expected_amount IS NOT NULL
                 AND evidence.observed_total = evidence.expected_amount
                THEN 'PAID'
            WHEN evidence.transaction_count > 0
                 AND evidence.active_rank > 1
                THEN 'SUPERSEDED'
            WHEN evidence.transaction_count > 0
                 AND evidence.expected_amount IS NULL
                THEN 'REQUIRES_REVIEW'
            WHEN evidence.transaction_count > 0
                 AND evidence.observed_total < evidence.expected_amount
                THEN 'PROCESSING'
            WHEN evidence.transaction_count > 0
                 AND evidence.observed_total > evidence.expected_amount
                THEN 'REQUIRES_REVIEW'
            WHEN evidence.current_status = 'PAID'
                 AND evidence.active_rank = 1
                THEN 'REQUIRES_REVIEW'
            WHEN evidence.current_status = 'PAID'
                THEN 'SUPERSEDED'
            ELSE evidence.current_status
        END AS desired_status
    FROM ranked_evidence evidence
)
UPDATE public.payment_requests pr
SET status = desired.desired_status,
    updated_at = CURRENT_TIMESTAMP
FROM desired_request_status desired
WHERE desired.payment_request_id = pr.payment_request_id
  AND pr.status IS DISTINCT FROM desired.desired_status;

-- Mark one-time legacy reconciliation ownership in a dedicated column. Provider
-- payload is intentionally replaceable runtime evidence and cannot safely own
-- migration bookkeeping.
UPDATE public.payment_requests
SET legacy_reconciliation_version = 'V20260716'
WHERE provider = 'PayOS'
  AND provider_payload ->> '_source' IN (
      'legacy_payment_transaction',
      'bookings_legacy_cache'
  )
  AND legacy_reconciliation_version IS DISTINCT FROM 'V20260716';

-- Preserve only runtime-compatible SHA-256 fingerprints and deterministically
-- clear any duplicate before enforcing uniqueness.
WITH ranked_fingerprints AS (
    SELECT
        payment_transaction_id,
        ROW_NUMBER() OVER (
            PARTITION BY channel, capture_fingerprint
            ORDER BY
                created_at NULLS LAST,
                payment_transaction_id
        ) AS fingerprint_rank
    FROM public.payment_transactions
    WHERE provider_transaction_id IS NULL
      AND capture_fingerprint IS NOT NULL
)
UPDATE public.payment_transactions pt
SET capture_fingerprint = NULL
FROM ranked_fingerprints ranked
WHERE ranked.payment_transaction_id = pt.payment_transaction_id
  AND ranked.fingerprint_rank > 1;

CREATE UNIQUE INDEX IF NOT EXISTS uq_payment_transactions_channel_capture_fingerprint
    ON public.payment_transactions(channel, capture_fingerprint)
    WHERE provider_transaction_id IS NULL
      AND capture_fingerprint IS NOT NULL;

-- Aggregate anomalies produce one alert per payment request, not one alert per
-- contributing split transfer.
WITH request_alert_evidence AS (
    SELECT
        pt.payment_request_id,
        CASE
            WHEN BOOL_OR(
                pt.reconciliation_status = 'AmountMismatch'
            ) THEN 'AmountMismatch'
            ELSE 'Unexpected'
        END AS reconciliation_status,
        MIN(pt.payment_transaction_id) AS representative_transaction_id,
        MIN(pt.booking_id) AS booking_id,
        MIN(pt.order_code) AS order_code,
        MIN(pt.payment_link_id) AS payment_link_id,
        SUM(pt.amount) AS observed_total,
        pr.amount AS expected_amount
    FROM public.payment_transactions pt
    JOIN public.payment_requests pr
      ON pr.payment_request_id = pt.payment_request_id
    WHERE pt.channel = 'PayOS'
      AND pt.legacy_reconciliation_version = 'V20260716'
      AND pt.reconciliation_status IN (
          'AmountMismatch',
          'Unexpected'
      )
    GROUP BY
        pt.payment_request_id,
        pr.amount
)
INSERT INTO public.system_alerts (
    type,
    severity,
    message,
    metadata,
    resolved,
    created_at
)
SELECT
    CASE evidence.reconciliation_status
        WHEN 'AmountMismatch' THEN 'PayOSAmountMismatch'
        ELSE 'PayOSUnexpectedTransaction'
    END,
    'High',
    CASE evidence.reconciliation_status
        WHEN 'AmountMismatch' THEN 'Legacy PayOS transactions exceed the expected payment request amount.'
        ELSE 'Legacy PayOS transaction has no reliable expected payment request amount.'
    END,
    jsonb_build_object(
        'paymentTransactionId',
            evidence.representative_transaction_id,
        'paymentRequestId', evidence.payment_request_id,
        'bookingId', evidence.booking_id,
        'orderCode', evidence.order_code,
        'paymentLinkId', evidence.payment_link_id,
        'observedTotal', evidence.observed_total,
        'expectedAmount', evidence.expected_amount
    ),
    FALSE,
    CURRENT_TIMESTAMP
FROM request_alert_evidence evidence
WHERE NOT EXISTS (
    SELECT 1
    FROM public.system_alerts sa
    WHERE sa.type = CASE evidence.reconciliation_status
        WHEN 'AmountMismatch' THEN 'PayOSAmountMismatch'
        ELSE 'PayOSUnexpectedTransaction'
    END
      AND sa.metadata ->> 'paymentRequestId'
          = evidence.payment_request_id::TEXT
);

-- A transaction with no trustworthy request remains independently actionable.
INSERT INTO public.system_alerts (
    type,
    severity,
    message,
    metadata,
    resolved,
    created_at
)
SELECT
    'PayOSOrphanTransaction',
    'High',
    'Legacy PayOS transaction could not be linked to a payment request.',
    jsonb_build_object(
        'paymentTransactionId', pt.payment_transaction_id,
        'bookingId', pt.booking_id,
        'orderCode', pt.order_code,
        'paymentLinkId', pt.payment_link_id,
        'reference', pt.provider_transaction_id,
        'amount', pt.amount
    ),
    FALSE,  
    CURRENT_TIMESTAMP
FROM public.payment_transactions pt
WHERE pt.channel = 'PayOS'
  AND pt.legacy_reconciliation_version = 'V20260716'
  AND pt.reconciliation_status = 'Orphan'
  AND NOT EXISTS (
      SELECT 1
      FROM public.system_alerts sa
      WHERE sa.type = 'PayOSOrphanTransaction'
        AND sa.metadata ->> 'paymentTransactionId'
            = pt.payment_transaction_id::TEXT
  );

COMMENT ON TABLE public.payment_requests IS
