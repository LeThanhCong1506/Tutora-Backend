-- Expand payment persistence so PayOS link/request data and actual bank
-- transactions have separate ownership. Booking PayOS columns are intentionally
-- retained in this release as a rollback/backfill source; application code no
-- longer writes them.

BEGIN;

CREATE TABLE IF NOT EXISTS public.payment_requests (
    payment_request_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id               INTEGER NOT NULL,
    user_id                  VARCHAR(50),
    provider                 VARCHAR(20) NOT NULL DEFAULT 'PayOS',
    phase                    VARCHAR(20) NOT NULL,
    order_code               BIGINT,
    payment_link_id          VARCHAR(255),
    amount                   NUMERIC(15, 2),
    currency                 VARCHAR(10) NOT NULL DEFAULT 'VND',
    status                   VARCHAR(30) NOT NULL,
    destination_bank_bin     VARCHAR(20),
    destination_bank_name    VARCHAR(100),
    display_account_number   VARCHAR(50),
    display_account_name     VARCHAR(200),
    description              TEXT,
    checkout_url             TEXT,
    qr_code                  TEXT,
    expires_at               TIMESTAMP WITHOUT TIME ZONE,
    provider_payload         JSONB,
    legacy_reconciliation_version VARCHAR(30),
    created_at               TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at               TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT payment_requests_booking_id_fkey
        FOREIGN KEY (booking_id) REFERENCES public.bookings(booking_id) ON DELETE RESTRICT,
    CONSTRAINT payment_requests_user_id_fkey
        FOREIGN KEY (user_id) REFERENCES public.users(user_id) ON DELETE SET NULL,
    CONSTRAINT ck_payment_requests_phase
        CHECK (phase IN ('deposit', 'remaining', 'legacy_unknown')),
    CONSTRAINT ck_payment_requests_status
        CHECK (status IN (
            'PENDING', 'PROCESSING', 'PAID', 'CANCELLED',
            'EXPIRED', 'SUPERSEDED', 'REQUIRES_REVIEW', 'UNKNOWN'
        )),
    CONSTRAINT ck_payment_requests_amount
        CHECK (amount IS NULL OR amount > 0)
);

