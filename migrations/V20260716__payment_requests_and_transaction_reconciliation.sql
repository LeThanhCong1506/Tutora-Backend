    reconciliation_status = 'Matched',
    capture_fingerprint = NULL,
    provider_code = COALESCE(
        NULLIF(BTRIM(
            expanded.element_payload ->> 'code'
        ), ''),
        pt.provider_code
    ),
    provider_desc = COALESCE(
        NULLIF(BTRIM(
            expanded.element_payload ->> 'desc'
        ), ''),
        pt.provider_desc
    ),
    source_account_bank_id = NULLIF(NULLIF(BTRIM(
        expanded.element_payload ->> 'counterAccountBankId'
    ), ''), '0'),
    source_account_bank_name = NULLIF(NULLIF(BTRIM(
        expanded.element_payload ->> 'counterAccountBankName'
    ), ''), '0'),
    source_account_number = NULLIF(NULLIF(BTRIM(
        expanded.element_payload ->> 'counterAccountNumber'
    ), ''), '0'),
    source_account_name = NULLIF(NULLIF(BTRIM(
        expanded.element_payload ->> 'counterAccountName'
    ), ''), '0'),
    destination_account_number = NULLIF(NULLIF(BTRIM(
        expanded.element_payload ->> 'accountNumber'
